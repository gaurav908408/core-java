class MYWrap {
    public static void main(String[] args) {

        String a = "4";
        String b = "4";

        String c = a + b;
        System.out.println("the value of c is:" + c);

        int x = Integer.parseInt(a);
        int y = Integer.parseInt(b);

        int z = x + y;
        System.out.println("the value of z is:" + z);
    }
}